#!/usr/bin/env python3
"""Writes the G3 table (verify/g3-code-layer.md) from the files of one run. Run inside the container:
  verify/run.sh python3 /crate/verify/mutants/report.py RUN [OUTPUT.md]
The verdict of every mutant comes from verdict.decide(); this file only formats it."""
import os
import re
import sys

import mutate
import verdict

run = sys.argv[1]
output = sys.argv[2] if len(sys.argv) > 2 else "/crate/verify/g3-code-layer.md"


def compact(text):
    text = text.replace("EmEventLoop.Answer.", "").replace("Aeneas.Std.Result.ok ", "")
    return re.sub(r"\s+", " ", text).strip()


def observations(mutant_id):
    log = open(f"{run}/mutants/{mutant_id}/counter.log").read()
    return [compact(part) for part in re.split(r"\n(?=\(|Aeneas|Aeneas.Std.Result)", log) if part.strip()]


rows = []
details = []
for mutant_id, (rule, what, _, ce) in mutate.MUTANTS.items():
    v = verdict.decide(run, mutant_id)
    # cargo test exits 101 when tests fail; anything else (a timeout, a crash) is not a catch
    if v.rust_rc == "101" and v.rust_failed.isdigit() and int(v.rust_failed) > 0:
        caught_rust = "yes"
    elif v.rust_rc == "0" and v.rust_failed == "0":
        caught_rust = "NO"
    else:
        caught_rust = f"ERROR (cargo test exit {v.rust_rc})"
    tests = int(v.rust_passed) + int(v.rust_failed) if v.rust_passed.isdigit() and v.rust_failed.isdigit() else "?"
    rows.append(
        f"| {mutant_id} | {rule} | {what} | {mutate.EXPECTED_OPERATION[mutant_id]} "
        f"| {'caught' if v.caught else 'NOT CAUGHT: ' + '; '.join(v.reasons)}: {', '.join(v.failing_refines)} "
        f"| {caught_rust} ({v.rust_failed} of {tests} tests fail) |")
    if "custom" in ce:
        shown, obs = "see the custom check in the counter-example file", []
    else:
        shown = f"budgets {ce['budgets']}, handlers {ce['handlers']}, script {ce['script']}"
        obs = observations(mutant_id) if v.caught else []
    details.append((mutant_id, rule, what, shown, obs, v))

out = ["# G3 code layer: planted bugs in the Rust, caught by the refinement proof\n",
       "Generated by `verify/mutants/report.py` from a run of `verify/mutants/run-all.sh` "
       "(`mutate.py` has the bugs, `run-mutant.sh` the steps, `verdict.py` the one function that decides). "
       "Each bug is planted in a disposable copy of `src/lib.rs` under `/cache`, never in the crate. "
       "For each mutant: (1) the copy compiles with `cargo` on nightly-2026-09-17, (2) Charon and Aeneas "
       "extract it, (3) the extracted `Types.lean` and `Funs.lean` and the unchanged `Abstraction.lean` "
       "elaborate in Lean (otherwise the mutant is invalid and the gate fails), (4) the unchanged "
       "`Refinement.lean` is compiled against them; Lean must exit 1, and the audit of "
       "`AuditAxioms.lean`, run at the end of that file, must show that the `*_refines` theorem of the "
       "expected operation depends on `sorryAx` (it no longer checks), (5) a counter-example script "
       "is run on the extracted mutant (`native_decide`) and on the reference implementation "
       "(which meets the step spec); the named theorem `counter` says that the two differ. The last "
       "column runs the crate's Rust tests on the mutant.\n",
       "| Mutant | Rule | Planted bug | Expected operation | Verdict: refinement theorems that no longer check | Rust tests catch it |",
       "|---|---|---|---|---|---|"] + rows
out.append("\n## Counter-examples\n")
out.append("Each script is a list of calls of the application (`rdy i b` = `set_ready`, `pau i b` = `set_paused`, "
           "`deadline h d`, `deadlinePaused h b`, `beginPass now`, `next` = `next_turn`). The observation is "
           "(answers of `next_turn`, per source (ready, paused, budget), per handler (deadline, paused), "
           "`next_deadline()`, `has_ready_source()`) after the script. The reference result is the one the "
           "step relation allows (`refOps_meets` and the `*_exactly_one` theorems).\n")
for mutant_id, rule, what, shown, obs, v in details:
    out.append(f"### {mutant_id} ({rule}): {what}\n")
    out.append(f"* Script: {shown}")
    if len(obs) >= 2:
        out.append(f"* Mutant (extracted code): `{obs[0]}`")
        out.append(f"* Spec (reference): `{obs[1]}`")
    elif obs:
        out.append(f"* Output: `{obs[0]}`")
    out.append(f"* Refinement theorems that no longer check: {', '.join(v.failing_refines)}")
    out.append(f"* Rust tests on the mutant: {v.rust_passed} passed, {v.rust_failed} failed: "
               f"{v.rust_failing_tests.strip() or 'none'}\n")
open(output, "w").write("\n".join(out) + "\n")
