    def test_check_passes_on_a_fresh_fixture_and_fails_when_stale(self):
        self.put("g", BUILD, BUILD)
        self.assertEqual(self.invoke("--group", "g")[0], 0)
        self.assertEqual(self.invoke("--check", "--group", "g")[0], 0)
        # Both builds change together, so they still agree, but the fixture is now stale.
        newer = BUILD.replace("0002", "0004")
        self.put("g", newer, newer)
        code, _, err = self.invoke("--check", "--group", "g")
        self.assertEqual(code, 1)
        self.assertIn("missing or stale", err)

    def test_check_fails_when_the_fixture_was_edited_by_hand(self):
        self.put("g", BUILD, BUILD)
        self.invoke("--group", "g")
        fixture = self.dir / "g.tsv"
        fixture.write_text(fixture.read_text().replace("0002", "0005"))
        self.assertEqual(self.invoke("--check", "--group", "g")[0], 1)

    def test_check_fails_when_the_fixture_is_missing(self):
        self.put("g", BUILD, BUILD)
        self.assertEqual(self.invoke("--check", "--group", "g")[0], 1)

    def test_check_does_not_write(self):
        self.put("g", BUILD, BUILD)
        self.invoke("--check", "--group", "g")
        self.assertFalse((self.dir / "g.tsv").exists())

    def test_one_bad_group_prevents_every_write(self):
        self.put("good", BUILD, BUILD)
        self.put("bad", BUILD, BUILD.replace("0002", "0003"))
        code, _, err = self.invoke()
        self.assertEqual(code, 1)
        self.assertIn("group bad", err)
        self.assertEqual(sorted(path.name for path in self.dir.glob("*.tsv") if path.name.count(".") == 1), [])

    def test_failed_rebuild_keeps_the_previous_fixture(self):
        self.put("g", BUILD, BUILD)
        self.invoke("--group", "g")
        before = (self.dir / "g.tsv").read_bytes()
